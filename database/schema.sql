\set ON_ERROR_STOP on

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

DROP TABLE IF EXISTS benchmark_sessions;
DROP TABLE IF EXISTS appointments;
DROP TABLE IF EXISTS doctor_patients;
DROP TABLE IF EXISTS visits;
DROP TABLE IF EXISTS doctors;
DROP TABLE IF EXISTS benchmark_users;
DROP TABLE IF EXISTS patients;

CREATE TABLE patients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id uuid NOT NULL UNIQUE,
    document varchar(20) NOT NULL UNIQUE,
    first_name varchar(80) NOT NULL,
    last_name varchar(80) NOT NULL,
    birth_date date NOT NULL,
    email varchar(254) NOT NULL UNIQUE,
    phone varchar(30),
    created_at timestamptz(3) NOT NULL,
    updated_at timestamptz(3) NOT NULL,
    CONSTRAINT patients_birth_date_check CHECK (birth_date >= DATE '1900-01-01' AND birth_date <= DATE '2020-12-31')
);

CREATE INDEX patients_last_name_id_idx ON patients (last_name, id);
CREATE INDEX patients_name_search_idx ON patients (lower(last_name) text_pattern_ops, lower(first_name) text_pattern_ops, id);

CREATE TABLE benchmark_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL,
    display_name varchar(120) NOT NULL,
    created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT benchmark_users_role_check CHECK (role IN ('admin', 'doctor', 'reception'))
);

CREATE TABLE doctors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES benchmark_users (id) ON DELETE RESTRICT,
    license_number varchar(30) NOT NULL UNIQUE,
    specialty varchar(80) NOT NULL,
    created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE visits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id bigint NOT NULL REFERENCES patients (id) ON DELETE RESTRICT,
    doctor_id bigint REFERENCES doctors (id) ON DELETE RESTRICT,
    visited_at timestamptz(3) NOT NULL,
    type varchar(20) NOT NULL,
    notes varchar(1000),
    created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT visits_type_check CHECK (type IN ('consultation', 'follow_up', 'emergency', 'telemedicine'))
);

CREATE INDEX visits_patient_visited_id_idx ON visits (patient_id, visited_at DESC, id DESC);
CREATE INDEX visits_doctor_visited_id_idx ON visits (doctor_id, visited_at DESC, id DESC);

CREATE TABLE doctor_patients (
    doctor_id bigint NOT NULL REFERENCES doctors (id) ON DELETE CASCADE,
    patient_id bigint NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    assigned_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (doctor_id, patient_id)
);

CREATE INDEX doctor_patients_patient_doctor_idx ON doctor_patients (patient_id, doctor_id);

CREATE TABLE appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id bigint NOT NULL REFERENCES patients (id) ON DELETE RESTRICT,
    doctor_id bigint NOT NULL REFERENCES doctors (id) ON DELETE RESTRICT,
    scheduled_at timestamptz(3) NOT NULL,
    status varchar(20) NOT NULL,
    reason varchar(255) NOT NULL,
    created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT appointments_status_check CHECK (status IN ('scheduled', 'confirmed', 'completed', 'cancelled'))
);

CREATE INDEX appointments_doctor_scheduled_id_idx ON appointments (doctor_id, scheduled_at, id);
CREATE INDEX appointments_patient_scheduled_id_idx ON appointments (patient_id, scheduled_at DESC, id DESC);

CREATE TABLE benchmark_sessions (
    token_hash char(64) PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES benchmark_users (id) ON DELETE CASCADE,
    csrf_token char(64) NOT NULL,
    expires_at timestamptz(3) NOT NULL,
    created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX benchmark_sessions_user_expires_idx ON benchmark_sessions (user_id, expires_at);
CREATE INDEX benchmark_sessions_expires_idx ON benchmark_sessions (expires_at);
